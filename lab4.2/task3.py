import numpy as np

# Матрица коэффициентов A (4 уравнения, 4 переменные)
A = np.array([
    [-2.0, -3.4, -6.4,  7.5],
    [ 0.5,  2.4,  0.0,  8.2],
    [ 8.5,  6.6,  7.1,  3.5],
    [ 2.3, -0.4, -9.8,  3.6]
])

# Вектор правых частей B
B = np.array([-1.24, -2.78, -3.5, -6.23])

# Решение системы: X = A⁻¹ · B
X = np.linalg.solve(A, B)

# Округление до одного знака после запятой
X_rounded = np.round(X, 1)

# Вывод результата
print("Решение системы:")
for i, x in enumerate(X_rounded, start=1):
    print(f"x{i} = {x}")
